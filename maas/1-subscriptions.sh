#!/bin/bash
# 1/4 Generates, for each MaaS tenant, ONE MaaSSubscription and ONE MaaSAuthPolicy that cover all the MaaSModelRefs of its
# namespace with the same default token limit. Rerun it after deploying (or deleting) a model: the same two resources are
# updated (oc apply), so the new model joins the subscription and a deleted one leaves it.
#
#   maas/1-subscriptions.sh                          # every tenant (AITenant)
#   maas/1-subscriptions.sh maas-keycloak            # a tenant by name (the AITenant) ...
#   maas/1-subscriptions.sh ai-tenant-maas-keycloak  # ... or by namespace; several can be given
#   maas/1-subscriptions.sh --dry-run                # server-side validation, applies nothing
#   LIMIT=50000 WINDOW=1m GROUPS_LIST=cluster-admins,team-a maas/1-subscriptions.sh models-as-a-service
#
# Variables: NAME (default all-models), LIMIT (100000), WINDOW (1h), GROUPS_LIST (system:authenticated, comma separated),
# PRIORITY (0), EXCLUDE (comma separated MaaSModelRef names that keep their own subscription, e.g. the demo simulator).
# A subscription lives in the namespace of its tenant: each tenant has its own maas-api and gateway, so it cannot cover models of
# two tenants. The groups of a Keycloak tenant are the ones of its token (groups claim). Next: maas/2-api-key.sh.
# The resources are not in git: the Argo CD applications use prune: false, so they are left alone.

set -euo pipefail

DRY_RUN=false; TENANTS=()
for a in "$@"; do [[ "$a" == "--dry-run" ]] && DRY_RUN=true || TENANTS+=("$a"); done

NAME="${NAME:-all-models}"
LIMIT="${LIMIT:-100000}"
WINDOW="${WINDOW:-1h}"
GROUPS_LIST="${GROUPS_LIST:-system:authenticated}"
PRIORITY="${PRIORITY:-0}"
EXCLUDE="${EXCLUDE:-}"

oc whoami &> /dev/null || { echo "❌ You are not logged in. Please log in and run the script again." >&2; exit 1; }

AITENANTS=$(oc get aitenant -A -o json)
# "name or namespace" -> namespace of the tenant
resolve() { jq -r --arg t "$1" '[.items[] | select(.metadata.name == $t or .status.tenantNamespace == $t) | .status.tenantNamespace][0] // empty' <<< "$AITENANTS"; }

NAMESPACES=()
if [[ ${#TENANTS[@]} -eq 0 ]]; then
    mapfile -t NAMESPACES < <(jq -r '.items[] | .status.tenantNamespace // empty' <<< "$AITENANTS")
else
    for t in "${TENANTS[@]}"; do
        NS=$(resolve "$t"); [[ -n "$NS" ]] || { echo "❌ '$t' is neither an AITenant nor the namespace of one. Tenants: $(jq -r '[.items[].metadata.name]|join(", ")' <<< "$AITENANTS")" >&2; exit 1; }
        NAMESPACES+=("$NS")
    done
fi
[[ ${#NAMESPACES[@]} -gt 0 ]] || { echo "❌ No tenant found (no AITenant)." >&2; exit 1; }

for NS in "${NAMESPACES[@]}"; do
    MODELS=$(oc get maasmodelref -n "$NS" -o json | jq -c --arg ex "$EXCLUDE" \
        '[.items[].metadata.name] | map(select(. as $n | ($ex | split(",") | index($n)) | not)) | sort')
    if [[ "$MODELS" == "[]" ]]; then echo "⏭️  $NS: no MaaSModelRef, nothing to do" >&2; continue; fi

    MANIFEST=$(jq -n --arg ns "$NS" --arg name "$NAME" --arg limit "$LIMIT" --arg window "$WINDOW" --arg prio "$PRIORITY" \
        --arg groups "$GROUPS_LIST" --argjson models "$MODELS" '
        ($groups | split(",") | map({name: .})) as $g
        | {apiVersion: "v1", kind: "List", items: [
            {apiVersion: "maas.opendatahub.io/v1alpha1", kind: "MaaSSubscription",
             metadata: {name: $name, namespace: $ns,
                        annotations: {"openshift.io/display-name": "All models of \($ns)",
                                      "openshift.io/description": "Generated by maas/1-subscriptions.sh: every MaaSModelRef of the namespace"}},
             spec: {modelRefs: ($models | map({name: ., namespace: $ns, tokenRateLimits: [{limit: ($limit|tonumber), window: $window}]})),
                    owner: {groups: $g}, priority: ($prio|tonumber)}},
            {apiVersion: "maas.opendatahub.io/v1alpha1", kind: "MaaSAuthPolicy",
             metadata: {name: "\($name)-policy", namespace: $ns,
                        annotations: {"openshift.io/description": "Generated by maas/1-subscriptions.sh"}},
             spec: {modelRefs: ($models | map({name: ., namespace: $ns})), subjects: {groups: $g}}}]}')

    if $DRY_RUN; then
        echo "# $NS: $(jq -r 'join(", ")' <<< "$MODELS")" >&2
        oc apply --dry-run=server -f - <<< "$MANIFEST"
    else
        oc apply -f - <<< "$MANIFEST" >/dev/null
        echo "✅ $NS: $NAME + $NAME-policy cover $(jq -r 'length' <<< "$MODELS") model(s): $(jq -r 'join(", ")' <<< "$MODELS")" >&2
    fi
done
